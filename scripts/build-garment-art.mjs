#!/usr/bin/env node
/**
 * Bakes the drawn garment plates into src/lib/garmentArt.ts.
 *
 * The plates are hand-drawn SVG — technical flats with the textile treatment
 * carrying the colour rhythm. They are baked into a plain TS module rather than
 * imported with Vite's `?raw` glob because scripts/test-demo.mjs bundles
 * demoData with esbuild, which does not understand import.meta.glob.
 *
 * Usage: node scripts/build-garment-art.mjs <source-dir>
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, basename, extname } from 'node:path';

const src = process.argv[2];
if (!src) {
  console.error('usage: node scripts/build-garment-art.mjs <source-dir>');
  process.exit(2);
}

const OUT = new URL('../src/lib/garmentArt.ts', import.meta.url).pathname;
const files = readdirSync(src).filter(f => extname(f) === '.svg').sort();

const entries = [];
const rejected = [];

for (const file of files) {
  const id = basename(file, '.svg');
  let svg = readFileSync(join(src, file), 'utf8').trim();

  // The plate is inlined into a data-URI and must never reach the network.
  // xmlns is the one permitted http:// token and encodeURIComponent escapes it.
  const withoutXmlns = svg.replace(/xmlns(:\w+)?="[^"]*"/g, '');
  for (const [rule, bad] of [
    ['remote reference', /https?:\/\//.test(withoutXmlns)],
    ['script', /<script/i.test(svg)],
    ['raster or external image', /<image[\s>]/i.test(svg)],
    ['xlink href', /xlink:href/i.test(svg)],
    ['foreignObject', /<foreignObject/i.test(svg)],
    ['text element', /<text[\s>]/i.test(svg)],
    ['not an svg root', !/^<svg[\s>]/i.test(svg)],
  ]) {
    if (bad) {
      rejected.push(`${file}: ${rule}`);
      svg = null;
      break;
    }
  }
  if (!svg) continue;

  // Collapse the whitespace a hand-drawn file carries; it is pure payload here.
  // Every run becomes ONE space — never nothing. Deleting single newlines welded
  // `d="…Z"` to the next attribute (`Z"fill=`), which broke five plates at once.
  svg = svg.replace(/\s+/g, ' ').replace(/> </g, '><');
  entries.push([id, svg]);
}

if (rejected.length) {
  console.error('REJECTED:\n  ' + rejected.join('\n  '));
  process.exit(1);
}

const body = entries
  .map(([id, svg]) => `  ${JSON.stringify(id)}: ${JSON.stringify(svg)},`)
  .join('\n');

writeFileSync(
  OUT,
  `// GENERATED by scripts/build-garment-art.mjs — do not edit by hand.
//
// Drawn garment plates: technical flats with real construction detail, the
// textile carrying the colour rhythm. Every plate is self-contained SVG with no
// script, no <image>, and no remote reference, so the demo keeps the
// offline-first promise (scripts/test-demo.mjs asserts it).
//
// ${entries.length} plates.

export const GARMENT_ART: Record<string, string> = {
${body}
};
`
);

const bytes = entries.reduce((sum, [, svg]) => sum + svg.length, 0);
console.log(`Baked ${entries.length} garment plates (${(bytes / 1024).toFixed(0)}KB) into src/lib/garmentArt.ts`);
